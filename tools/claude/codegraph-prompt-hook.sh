#!/usr/bin/env bash
# UserPromptSubmit-фильтр перед `codegraph prompt-hook`.
#
# ЗАЧЕМ. Сам `codegraph prompt-hook` опций не имеет (`--help`: только `-h`) и
# срабатывает на КАЖДЫЙ user-turn, вкладывая в контекст ~16 КБ (≈5–6 тыс.
# токенов) «структурного контекста». Замер сессии 80d600f8 (2026-11-10):
# 16 user-turn — 16 срабатываний, из них 0 на вопрос о коде. Девять пришли
# на сообщения других сессий (`<agent-message …>`), уведомления о фоновых
# задачах (`<task-notification>`) и загрузку навыка; семь — на короткие
# концептуальные вопросы владельца по-русски. Хук при этом вытащил
# `AndroidPermissionChecker`, androidTest-пробы и превью-экраны — ноль
# релевантности. Двойная регистрация (проектная + пользовательская) тут ни
# при чём: харнесс дедуплицирует одинаковые команды, срабатывание одно.
#
# ЧТО ДЕЛАЕТ. Читает JSON события со stdin и зовёт настоящий хук только
# когда промт похож на вопрос о коде:
#   1. НЕ машинный и не вставка: нет `<agent-message`, `<task-notification`,
#      `<system-reminder`, `<pasted_content`, «Base directory for this skill».
#      Вставленный бриф сессии исследуется руками через `codegraph_explore`,
#      как и велит CLAUDE.md, — автоматический контекст по нему слепой.
#   2. ЕСТЬ хотя бы один токен в форме кода: CamelCase с двумя горбами
#      (`ToolSelector`), snake_case (`uninstall_app`), путь `.kt/.kts/.java`,
#      пакет `com.sidr…` или фрагмент в обратных кавычках.
# Иначе выходит молча с кодом 0 — для харнесса это «хук отработал, контекста
# нет». Исходный stdin передаётся настоящему хуку без изменений.
#
# ИЗВЕСТНЫЕ ПРЕДЕЛЫ, названные, а не скрытые:
#   - Эвристика, не понимание: «как работает выбор инструмента?» без единого
#     идентификатора контекста не получит; «запости в `#general`» — получит.
#     Ложный пропуск стоит одного ручного `codegraph_explore`, ложное
#     срабатывание — ~16 КБ контекста; перекос выбран в сторону пропуска.
#   - Калибровка по одной сессии. Пересчитать после трёх: доля срабатываний,
#     давших полезный контекст, — единственная метрика.
#
# Контракт: stdin — JSON `{prompt, cwd, …}`; stdout — то, что вернул
# настоящий хук, или ничего; код возврата 0 в обоих случаях.

set -uo pipefail

input="$(cat)"
prompt="$(printf '%s' "$input" | jq -r '.prompt // ""' 2>/dev/null)" || prompt=""
[ -z "$prompt" ] && exit 0

# 1. Машинные user-turn и вставки.
if printf '%s' "$prompt" | grep -Eq '<agent-message|<task-notification|<system-reminder|<pasted_content|Base directory for this skill'; then
  exit 0
fi

# 2. Токен в форме кода.
code_token='[A-Z][a-z0-9]+[A-Z][A-Za-z0-9]+|[a-z0-9]+_[a-z0-9_]+|[A-Za-z0-9_/-]+\.(kt|kts|java)\b|\bcom\.sidr\b|`[^`]+`'
if printf '%s' "$prompt" | grep -Eq "$code_token"; then
  printf '%s' "$input" | exec codegraph prompt-hook
fi

exit 0
