#!/usr/bin/env bash
# PreToolUse-страж для инструмента Bash.
#
# ЗАЧЕМ ХУК, А НЕ ПРАВИЛА deny. Правила Bash(...) в settings.json совпадают
# только точно или по ПРЕФИКСУ (справка CLI: `Bash(git *)` — "matches git,
# git status, git commit"). Внутренних подстановок нет, поэтому запрет вида
# Bash(./gradlew *<задача>*) не сработал бы НИКОГДА: и tools/gate.sh, и ручные
# вызовы ставят -P-аргументы ПЕРЕД именем задачи. Это был бы ровно тот
# недоказуемый страж, которых блок A1" насчитал восемь. Хук читает строку
# команды, и порядок аргументов ему безразличен.
#
# ЧТО ЗАПРЕЩАЕТ:
#   1. git-публикацию — правило проекта: агент коммитит, агент никогда не
#      пушит. Решение о публикации принимает владелец.
#   2. Gradle-прогон инструментальных тестов на устройстве — он
#      переустанавливает приложение на телефоне владельца и уничтожает его
#      базу schema-4, на которой стоит приёмка миграций. Санкционированный
#      путь — `adb shell am instrument` руками — не затронут.
#   3. gradlew с выводом в tail/head/less/more — маскирует красный гейт
#      нулевым кодом возврата (случилось 2026-07-13). Читайте лог целиком.
#
# ПОЧЕМУ СРАВНЕНИЕ ПОСЕГМЕНТНОЕ. Первая версия смотрела всю строку сразу и на
# первом же применении ложно заблокировала запись файла прав: слова `git` и
# `push` стояли в heredoc на РАЗНЫХ строках, в разных правилах, и ни одно из
# них не было вызовом. Поэтому строка режется по переводам строки, `;` и `&&`
# (но НЕ по одиночному `&` — иначе развалится `2>&1`), и оба условия правила
# должны сойтись внутри ОДНОГО сегмента.
#
# ИЗВЕСТНЫЕ ПРЕДЕЛЫ, названные, а не скрытые:
#   - Gradle понимает сокращения camelCase (`cAT`), и перечислить их все
#     нельзя. Покрыты литеральные формы и `cAT`; для `conAT`, `connAndroidT`
#     и прочих пробел остаётся открытым.
#   - Правило 1 сработает ложно на сегменте, где `git` и отдельный токен
#     `push` стоят рядом не как вызов (например `git add x && adb push y` в
#     одной строке без разделителя). Ложный блок громкий и дешёвый, ложный
#     пропуск тихий и дорогой — перекос выбран сознательно.
#
# Контракт: на stdin — JSON события, на stdout — решение, код 2 = блок.
# Оба канала заполняются нарочно: разные версии CLI читают разные.

set -uo pipefail

cmd="$(jq -r '.tool_input.command // ""' 2>/dev/null)" || cmd=""
[ -z "$cmd" ] && exit 0

refuse() {
  jq -Rn --arg m "$1" \
    '{hookSpecificOutput:{hookEventName:"PreToolUse",permissionDecision:"deny",permissionDecisionReason:$m}}'
  printf '%s\n' "$1" >&2
  exit 2
}

# Сегменты: переводы строки, `;`, `&&`. Одиночный `&` не трогаем.
segments="$(printf '%s' "$cmd" | sed 's/&&/\n/g; s/;/\n/g')"

while IFS= read -r seg; do
  [ -z "$seg" ] && continue
  m() { printf '%s' "$seg" | grep -Eq "$1"; }
  mi() { printf '%s' "$seg" | grep -Eqi "$1"; }

  # 1. Публикация в удалённый репозиторий. Между `git` и отдельным токеном
  #    публикации допускаются любые опции со значениями — так ловится форма
  #    `git -C <путь> …`, на которой провалилась первая регулярка, но не
  #    ловится `git log --grep=…`, где слово приклеено к `=`.
  if m '\bgit\b([[:space:]]+[^[:space:]]+)*[[:space:]]+push([[:space:]]|$)'; then
    refuse "Публикация в удалённый репозиторий запрещена правилом проекта: агент коммитит, агент никогда не пушит. Предложите коммит владельцу и остановитесь."
  fi

  # 2. Инструментальные тесты через Gradle. Требуется, чтобы gradle(w) и имя
  #    задачи стояли в одном сегменте — тогда упоминание задачи в документе
  #    или комментарии не блокируется, а настоящий вызов блокируется.
  if mi 'gradlew?[^|;&]*connected[a-z]*(androidtest|check)'; then
    refuse "Gradle-прогон инструментальных тестов запрещён: он переустановит приложение на телефоне владельца и уничтожит базу schema-4. Используйте 'adb shell am instrument' вручную."
  fi
  if m 'gradlew' && m '(^|[[:space:]])cAT([[:space:]]|$)'; then
    refuse "cAT — сокращение Gradle для инструментальных тестов, запрещено по той же причине: переустановка приложения на телефоне владельца."
  fi

  # 3. Вывод gradlew в усекающую команду.
  if m 'gradlew' && m '\|[[:space:]]*(tail|head|less|more)\b'; then
    refuse "Вывод gradlew нельзя направлять в tail/head/less/more: код возврата подменяется, и красный гейт выглядит как exit 0 (это уже случилось 2026-07-13). Проверяйте код возврата и читайте лог целиком."
  fi
done <<< "$segments"

exit 0
